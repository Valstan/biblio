/**
 * «Режим» области — **две небольшие кнопки** (промт КАРМАНА #177, п. 1).
 *
 * Раньше это была одна кнопка, у которой менялась надпись («Автомат» /
 * «Вручную»), и включённый вариант был виден только по тексту. Теперь обе
 * подписи **всегда на виду**, кнопки небольшие, а включённая — выделена.
 *
 * Вынесено в отдельный модуль, чтобы правила проверялись тестом, а не
 * глазами (как словарь водителя и сортировка областей).
 */

export interface ModeButton {
  /** Подпись кнопки — видна всегда. */
  label: string
  /** Что кнопка включает: `true` — автоматический режим, `false` — ручной. */
  autoheal: boolean
  /** Подсказка: что значит режим. */
  hint: string
}

/** Ровно две кнопки — обе подписи на виду всегда. */
export const MODE_BUTTONS: readonly ModeButton[] = [
  {
    label: 'Автомат',
    autoheal: true,
    hint: 'Автоматический режим: МиниГен сам меняет аккаунт и следит за очками. ' +
      'В сессию не уходит ни одного сообщения.'
  },
  {
    label: 'Вручную',
    autoheal: false,
    hint: 'Ручной режим: аккаунт и очки владелец меняет сам. ' +
      'В сессию не уходит ни одного сообщения.'
  }
]

/** Кнопка включённого режима. */
export function activeModeButton(autoheal: boolean): ModeButton {
  return MODE_BUTTONS.find((item) => item.autoheal === autoheal) ?? MODE_BUTTONS[0]
}
