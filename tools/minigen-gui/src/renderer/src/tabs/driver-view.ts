/**
 * Кто водит сессиями проекта (промт КАРМАНА #174, переформулировано в #177).
 *
 * Правило «один водитель на проект»: в каждый момент у проекта один водитель
 * сессий. Переключатель — в списке областей программы «МиниГен» (по
 * области/проекту).
 *
 * ⚠️ ПРОМТ КАРМАНА #177 (зачитка владельца 27.11): в переключателе **ровно
 * три** варианта, и слова — владельческие:
 *
 * - **Внешнее управление** — сессиями управляет внешний агент (созданный
 *   владельцем): он сам посылает команды и завершает их, а МиниГен только
 *   автоматически поставляет аккаунты с очками;
 * - **Управление МиниГеном** — встроенная в МиниГен нейросеть смотрит на вывод
 *   сессии (последнее слово, выводы «выполнила такую-то работу») и определяет,
 *   завершена ли работа; если завершена — посылает команду завершения, потом
 *   проверяет, что сессия закрылась корректно, архивирует её и поднимает
 *   новую с продолжением нитки разработки;
 * - **Оператор** — никто не управляет, оператор сам сидит и ведёт сессии.
 *
 * **Судьба «по правилу»** (решение владельца, зафиксировано здесь и в ядре —
 * `minigen_core.DRIVER_SWITCH_VALUES`): «по правилу» **уходит из
 * переключателя** — четвёртого пункта там нет (владелец просил три). В ядре
 * он остаётся **правилом по умолчанию** для области, где водитель ещё не
 * выбран явно: «если в области работает Управляющий, водит он, иначе
 * автомат». То есть водитель выбирается явно всегда, а «по правилу» — это
 * честное правило ядра для необъявленного выбора, а не вариант водителя.
 *
 * Вынесено в отдельный модуль, чтобы правила проверялись тестом, а не
 * глазами (как сортировка областей и карта генов).
 */

/**
 * Значения переключателя — **ровно три**, как в ядре
 * (`minigen_core.DRIVER_SWITCH_VALUES`).
 */
export const DRIVER_VALUES = ['manager', 'automaton', 'none'] as const

export type DriverValue = (typeof DRIVER_VALUES)[number]

/**
 * «По правилу» — правило ядра для необъявленного выбора. Это **не** пункт
 * переключателя: в меню его нет (промт КАРМАНА #177, п. 4).
 */
export const DRIVER_RULE = 'auto'

/** Человеческое имя значения переключателя — те же слова, что в ядре. */
export const DRIVER_LABELS: Record<DriverValue, string> = {
  manager: 'Внешнее управление',
  automaton: 'Управление МиниГеном',
  none: 'Оператор'
}

/**
 * Что значит каждое значение — словами (подсказка в окне): кто водит сессиями
 * и что делает.
 */
export const DRIVER_HINTS: Record<DriverValue, string> = {
  manager:
    'Сессиями управляет внешний агент (созданный владельцем): он сам посылает ' +
    'команды и завершает их, а МиниГен только автоматически поставляет аккаунты ' +
    'с очками — в сессии не пишет ничего',
  automaton:
    'Встроенная в МиниГен нейросеть смотрит на вывод сессии и определяет, ' +
    'завершена ли работа; если завершена — закрывает и архивирует сессию и ' +
    'поднимает новую с продолжением нитки',
  none: 'Никто не вмешивается в сессии: оператор сам сидит и ведёт сессии'
}

/** Область с переключателем водителя (значение и то, кто водит сейчас). */
export interface DriverArea {
  driver?: string
  driverNow?: {
    driver: string
    title: string
    why: string
    source: string
  }
}

/** Значение из переключателя (пустое — не из трёх). */
export function isDriverValue(value: unknown): value is DriverValue {
  return (DRIVER_VALUES as readonly string[]).includes(String(value ?? ''))
}

/**
 * Кто водит сессиями области **сейчас** — значение для переключателя.
 *
 * Порядок:
 * 1. в проекте выбрано явно ⇒ берём его;
 * 2. выбора нет (пусто / «по правилу») ⇒ водителя определяет ядро — берём его
 *    ответ (`driverNow`);
 * 3. ядро не ответило (старое ядро на машине) ⇒ пусто: выдумывать нельзя.
 */
export function driverValue(area: DriverArea): DriverValue | '' {
  const raw = String(area.driver ?? '').trim().toLowerCase()
  if (isDriverValue(raw)) return raw
  const now = String(area.driverNow?.driver ?? '').trim().toLowerCase()
  return isDriverValue(now) ? now : ''
}

/** Выбран ли водитель в проекте явно (а не «по правилу»). */
export function driverExplicit(area: DriverArea): boolean {
  return isDriverValue(String(area.driver ?? '').trim().toLowerCase())
}

/** Подпись значения переключателя (или «—», если водителя нет). */
export function driverLabel(area: DriverArea): string {
  const value = driverValue(area)
  return value ? DRIVER_LABELS[value] : '—'
}

/**
 * Подсказка к переключателю: что значит выбранное значение **и** кто водит
 * сессиями сейчас (и почему).
 */
export function driverHint(area: DriverArea): string {
  const value = driverValue(area)
  const base = value ? DRIVER_HINTS[value] : 'Водитель не определён'
  const now = area.driverNow
  if (!now?.title) return base
  const why = now.why ? ` — ${now.why}` : ''
  const rule = now.source === 'правило' ? ' (по правилу)' : ''
  return `${base}. Сейчас водит: ${now.title}${rule}${why}`
}
